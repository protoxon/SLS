package client

import (
	"context"
	"net/http"

	"protoxon.com/sls/controller/models"
	"protoxon.com/sls/internal/api"
)

type NodeClient interface {
	SetToken(token string)
	GetToken() string
	Server(id string) ServerClient

	// BaseURL is the node's HTTP origin, such as https://daemon.example:5585.
	BaseURL() string
	// Socket is the Unix socket for this node. Empty means dial BaseURL over TCP.
	Socket() string

	// Request types
	Get(ctx context.Context, path string, query q) (*Response, error)
	Post(ctx context.Context, path string, data interface{}) (*Response, error)
	Delete(ctx context.Context, path string) (*Response, error)

	// Requests
	CreateServer(context context.Context, request models.ServerConfiguration) (models.CreateServerResponse, error)
	ServerPresent(ctx context.Context, id string) (bool, error)
	GetSystemInformation(context context.Context) (models.Information, error)
	Sync(context context.Context) error
	RetainVolumes(ctx context.Context, artifacts []string) error
	StartSnapshot(ctx context.Context, serverID string, request api.CreateSnapshotRequest) error
}

type nodeClient struct {
	client  *Client
	nodeId  string
	baseUrl string
	socket  string

	// The token is generated by controller and is given
	// to the node for verification
	token string
}

// Server returns a server specific client bound to this node client.
func (nc *nodeClient) Server(id string) ServerClient {
	return NewServerClient(id, nc.nodeId).SetNodeClient(nc)
}

// SetToken sets the authentication token to use when making requests to the node
func (nc *nodeClient) SetToken(token string) {
	nc.token = token
}

// GetToken returns the authentication used for authenticating requests to the node
func (nc *nodeClient) GetToken() string {
	return nc.token
}

// BaseURL returns the node's HTTP origin.
func (nc *nodeClient) BaseURL() string {
	return nc.baseUrl
}

// Socket returns the Unix socket for this node, or empty when it is reached over TCP.
func (nc *nodeClient) Socket() string {
	return nc.socket
}

// CreateServer sends a request to create a new server on the remote node
// and returns the server's data upon successful creation.
func (nc *nodeClient) CreateServer(ctx context.Context, create models.ServerConfiguration) (models.CreateServerResponse, error) {
	return Post[models.CreateServerResponse](nc, ctx, "/servers", create)
}

// ServerPresent reports whether the daemon already has this server id.
// A 404 is present=false. Other failures are returned so the caller can keep
// the reservation instead of freeing a port the daemon might still be using.
func (nc *nodeClient) ServerPresent(ctx context.Context, id string) (bool, error) {
	res, err := nc.Get(ctx, "/servers/"+id+"/status", nil)
	if err != nil {
		if re := AsRequestError(err); re != nil && re.StatusCode() == http.StatusNotFound {
			return false, nil
		}
		return false, err
	}
	if res != nil && res.Body != nil {
		_ = res.Body.Close()
	}
	return true, nil
}

// Syncs the nodes server configurations with Controller
func (nc *nodeClient) Sync(ctx context.Context) error {
	_, err := nc.Post(ctx, "/sync", nil)
	return err
}

// RetainVolumes sends the blueprint artifact list so the node can drop unused caches.
func (nc *nodeClient) RetainVolumes(ctx context.Context, artifacts []string) error {
	if artifacts == nil {
		artifacts = []string{}
	}
	res, err := nc.Post(ctx, "/volumes/retain", struct {
		Artifacts []string `json:"artifacts"`
	}{Artifacts: artifacts})
	if res != nil && res.Body != nil {
		_ = res.Body.Close()
	}
	return err
}

// StartSnapshot asks the daemon to capture a server's overlay uppers.
func (nc *nodeClient) StartSnapshot(ctx context.Context, serverID string, request api.CreateSnapshotRequest) error {
	res, err := nc.Post(ctx, "/servers/"+serverID+"/snapshots", request)
	if res != nil && res.Body != nil {
		_ = res.Body.Close()
	}
	return err
}

// GetSystemInformation fetches system information from the nodes system package
func (nc *nodeClient) GetSystemInformation(ctx context.Context) (models.Information, error) {
	return Get[models.Information](nc, ctx, "/system", nil)
}
